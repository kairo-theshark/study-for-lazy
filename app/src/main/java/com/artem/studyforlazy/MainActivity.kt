// только иконки из material-icons-core: extended не подключён
private enum class Tab(val route: String, val title: String, val icon: ImageVector) {
    Schedule("schedule", "Расписание", Icons.Filled.DateRange),
    Alarm("alarm", "Будильник-садист", Icons.Filled.Notifications),
    Stats("stats", "Статистика проёбов", Icons.AutoMirrored.Filled.List),
}

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContent {
            StudyForLazyTheme {
                StudyForLazyApp()
            }
        }
    }
}

@Composable
fun StudyForLazyTheme(content: @Composable () -> Unit) {
    // тёмная тема всегда: приложение для вечерних/утренних мучений
    MaterialTheme(colorScheme = darkColorScheme(), content = content)
}

@Composable
fun StudyForLazyApp() {
    val navController = rememberNavController()
    val backStackEntry by navController.currentBackStackEntryAsState()
    val currentDestination = backStackEntry?.destination

    Scaffold(
        bottomBar = {
            NavigationBar {
                Tab.entries.forEach { tab ->
                    NavigationBarItem(
                        selected = currentDestination?.hierarchy?.any { it.route == tab.route } == true,
                        onClick = {
                            navController.navigate(tab.route) {
                                popUpTo(navController.graph.findStartDestination().id) { saveState = true }
                                launchSingleTop = true
                                restoreState = true
                            }
                        },
                        icon = { Icon(tab.icon, contentDescription = null) },
                        label = { Text(tab.title) },
                    )
                }
            }
        },
    ) { innerPadding ->
        NavHost(
            navController = navController,
            startDestination = Tab.Schedule.route,
            modifier = Modifier.padding(innerPadding),
        ) {
            Tab.entries.forEach { tab ->
                composable(tab.route) { PlaceholderScreen(tab.title) }
            }
        }
    }
}

@Composable
private fun PlaceholderScreen(title: String) {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(24.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp, Alignment.CenterVertically),
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        Text(
            text = title,
            style = MaterialTheme.typography.headlineMedium,
            textAlign = TextAlign.Center,
        )
        Text(
            text = "Экран в разработке",
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
    }
}

